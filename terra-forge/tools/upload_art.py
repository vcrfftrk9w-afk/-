"""Uploads the painted map chunks to Roblox as decals through Open Cloud and writes their
ids to src/shared/MapArt.luau. The game server turns decal ids into image ids at start.
The API key (assets read and write) comes from the cloud environment's network secret for
apis.roblox.com, or from ROBLOX_API_KEY.
Usage: python3 tools/gen_texture.py DIR && python3 tools/upload_art.py DIR
"""
import json
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = 'https://apis.roblox.com/assets/v1'
USER_ID = '11754622388'
CHUNKS = 8


def curl(args):
    key = os.environ.get('ROBLOX_API_KEY')
    extra = ['-H', f'x-api-key: {key}'] if key else []
    out = subprocess.run(['curl', '-sS', '-m', '180'] + extra + args, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def upload(path, name):
    request = {
        'assetType': 'Decal',
        'displayName': name,
        'description': 'Terra Forge world map',
        'creationContext': {'creator': {'userId': USER_ID}},
    }
    op = curl(['-X', 'POST', f'{API}/assets', '-F', f'request={json.dumps(request)};type=application/json',
               '-F', f'fileContent=@{path};type=image/png'])
    if 'operationId' not in op:
        raise RuntimeError(f'upload failed: {op}')
    for _ in range(60):
        res = curl([f'{API}/operations/{op["operationId"]}'])
        if res.get('done'):
            return res['response']['assetId']
        time.sleep(2)
    raise RuntimeError('upload did not finish')


def main():
    src = sys.argv[1]
    ids = []
    for n in range(CHUNKS):
        asset = upload(os.path.join(src, f'map_{n}.png'), f'Terra Forge map {n}')
        print(n, asset)
        ids.append(asset)
    lines = ['-- Generated by tools/upload_art.py. Do not edit by hand.',
             '-- Decal ids of the painted world map, one per ground chunk (4 x 2, row by row).',
             'return {', '\tmap = { ' + ', '.join(ids) + ' },', '}', '']
    open(os.path.join(ROOT, 'src', 'shared', 'MapArt.luau'), 'w', encoding='utf-8').write('\n'.join(lines))


if __name__ == '__main__':
    main()
