import { ProfileStats, COACH_ADVICE } from "./analysis";

export interface RoadmapTask {
  id: string;
  text: string;
}

export interface RoadmapPhase {
  id: string;
  title: string;
  period: string;
  goal: string;
  tasks: RoadmapTask[];
}

export function buildRoadmap(profile: ProfileStats): RoadmapPhase[] {
  const weakTips = profile.weakPoints.flatMap(
    (m) => COACH_ADVICE[m.key].tips.slice(0, 2),
  );

  const phase1: RoadmapPhase = {
    id: "phase-1",
    title: "Фаза 1 · Фундамент",
    period: "Дни 1–14",
    goal: "Стабилизировать публикации и найти свой формат",
    tasks: [
      { id: "p1-1", text: "Заполни шапку профиля: чёткая ниша в 1 фразе + актуальное фото" },
      { id: "p1-2", text: "Определи 3–4 контент-пилларa и распредели по ним ближайшие темы" },
      { id: "p1-3", text: "Публикуй минимум 5 видео в неделю без пропусков" },
      { id: "p1-4", text: weakTips[0] ?? "Проработай хук в первые 3 секунды каждого видео" },
      { id: "p1-5", text: "Изучи вкладку 'В тренде' каждый день по 5–10 минут" },
      { id: "p1-6", text: "Сними первое видео в формате из раздела 'Радар трендов'" },
    ],
  };

  const phase2: RoadmapPhase = {
    id: "phase-2",
    title: "Фаза 2 · Набор темпа",
    period: "Дни 15–30",
    goal: "Найти вирусный формат и закрепить регулярность",
    tasks: [
      { id: "p2-1", text: "Проанализируй 3 лучших видео месяца — найди общий паттерн хука/темы" },
      { id: "p2-2", text: "Удвой публикации в формате, который зашёл лучше всего" },
      { id: "p2-3", text: weakTips[1] ?? "Улучши удержание — убери провисания при монтаже" },
      { id: "p2-4", text: `Публикуй в оптимальное время: ${profile.bestSlot.day}, ${profile.bestSlot.slot}` },
      { id: "p2-5", text: "Сделай 1 дуэт/стич с популярным видео в своей нише" },
      { id: "p2-6", text: "Оптимизируй хэштеги: 2 нишевых + 2 широких + 1 трендовый" },
    ],
  };

  const phase3: RoadmapPhase = {
    id: "phase-3",
    title: "Фаза 3 · Ускорение",
    period: "Месяц 2",
    goal: "Масштабировать то, что работает, и выйти за пределы своей аудитории",
    tasks: [
      { id: "p3-1", text: "Запусти серию видео (часть 1/2/3) на основе самой залетевшей темы" },
      { id: "p3-2", text: "Коллаборация или дуэт с автором похожего размера в твоей нише" },
      { id: "p3-3", text: "Протестируй 2 новых формата из раздела 'Радар трендов' за неделю" },
      { id: "p3-4", text: "Введи рубрику с постоянным названием и обложкой для узнаваемости" },
      { id: "p3-5", text: "Проанализируй аналитику: источник трафика 'Рекомендации' должен расти" },
      { id: "p3-6", text: "Отвечай видео-ответами на 3 лучших комментария в неделю" },
    ],
  };

  const phase4: RoadmapPhase = {
    id: "phase-4",
    title: "Фаза 4 · Прорыв",
    period: "Месяц 3+",
    goal: "Закрепить статус и монетизировать аудиторию",
    tasks: [
      { id: "p4-1", text: "Сформируй фирменный стиль: узнаваемая подача, монтаж, цветокор" },
      { id: "p4-2", text: "Запусти мини-челлендж и предложи аудитории снять дуэты" },
      { id: "p4-3", text: "Начни кросс-постинг лучших видео в Reels/Shorts для доп. охвата" },
      { id: "p4-4", text: "Изучи Creator Fund/бренд-интеграции, если объём просмотров позволяет" },
      { id: "p4-5", text: "Проведи ревизию контент-плана раз в 2 недели по метрикам" },
      { id: "p4-6", text: "Выйди на новую под-нишу/формат, чтобы не выгорать и расти дальше" },
    ],
  };

  return [phase1, phase2, phase3, phase4];
}
