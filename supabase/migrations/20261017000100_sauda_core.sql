create table sauda.state (
  id int primary key default 1 check (id = 1),
  last_tick timestamptz not null default 'epoch'
);
insert into sauda.state default values;

-- ───────────── люди ─────────────
create table sauda.users (
  id uuid primary key default gen_random_uuid(),
  login text not null unique,
  name text not null,
  pass_hash text not null,
  avatar text not null default '',
  bio text not null default '',
  city text not null default '',
  lang text not null default 'ru',
  role text not null default 'user' check (role in ('user', 'moder', 'admin', 'bot')),
  balance bigint not null default 0,
  stars_sum int not null default 0,
  reviews int not null default 0,
  sales int not null default 0,
  purchases int not null default 0,
  verified boolean not null default false,
  pro_until timestamptz,
  banned boolean not null default false,
  ban_reason text not null default '',
  ref_code text not null unique default encode(extensions.gen_random_bytes(4), 'hex'),
  ref_by uuid references sauda.users(id),
  is_demo boolean not null default false,
  fails int not null default 0,
  locked_until timestamptz,
  rate_at timestamptz not null default now(),
  rate_n int not null default 0,
  last_seen timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint balance_ok check (balance >= 0 or role = 'bot')
);

create table sauda.sessions (
  token_hash text primary key,
  user_id uuid not null references sauda.users(id) on delete cascade,
  device text not null default '',
  created_at timestamptz not null default now(),
  last_seen timestamptz not null default now()
);
create index on sauda.sessions(user_id);

-- ───────────── каталог ─────────────
-- sections: [{ id, ru, kz }]; id — одно из: accounts currency donate items boost keys topup subs services coaching goods other
create table sauda.games (
  id text primary key,
  name text not null,
  kind text not null check (kind in ('mobile', 'pc', 'subs', 'social', 'service', 'goods')),
  emoji text not null default '🎮',
  color text not null default '#00afca',
  sort int not null default 100,
  popular boolean not null default false,
  sections jsonb not null default '[]'
);

create table sauda.lots (
  id bigint generated by default as identity (start with 10001) primary key,
  seller uuid not null references sauda.users(id),
  game text not null references sauda.games(id),
  section text not null,
  title text not null,
  descr text not null default '',
  price bigint not null check (price between 10 and 10000000),
  old_price bigint,
  qty int check (qty is null or qty >= 0),              -- null — без лимита (услуги)
  auto boolean not null default false,                  -- автовыдача из sauda.lot_items
  needs_id boolean not null default false,              -- покупатель указывает ID игрока / почту
  id_label text not null default '',
  deliver_mins int not null default 60 check (deliver_mins between 1 and 20160),
  period_days int check (period_days is null or period_days between 1 and 366), -- подписка: срок, можно автопродление
  attrs jsonb not null default '{}',
  city text not null default '',
  thumb text not null default '',
  images jsonb not null default '[]',
  status text not null default 'active' check (status in ('active', 'paused', 'sold', 'deleted', 'blocked')),
  views int not null default 0,
  sold int not null default 0,
  is_demo boolean not null default false,
  raised_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on sauda.lots(game, section, status, raised_at desc);
create index on sauda.lots(seller, status);
create index on sauda.lots(status, raised_at desc);
create index on sauda.lots using gin (lower(title) extensions.gin_trgm_ops);

-- товары для автовыдачи: по одному на строку (код, ключ, логин:пароль)
create table sauda.lot_items (
  id bigint generated by default as identity primary key,
  lot_id bigint not null references sauda.lots(id) on delete cascade,
  payload text not null,
  order_id bigint,
  created_at timestamptz not null default now()
);
create index on sauda.lot_items(lot_id) where order_id is null;
create index on sauda.lot_items(order_id) where order_id is not null;

-- ───────────── сделки ─────────────
create table sauda.orders (
  id bigint generated by default as identity (start with 100001) primary key,
  lot_id bigint not null references sauda.lots(id),
  buyer uuid not null references sauda.users(id),
  seller uuid not null references sauda.users(id),
  game text not null,
  section text not null,
  title text not null,
  unit_price bigint not null,
  qty int not null,
  amount bigint not null,
  fee bigint not null default 0,
  status text not null check (status in ('paid', 'delivered', 'completed', 'refunded', 'dispute')),
  buyer_data text not null default '',
  payload text not null default '',
  auto boolean not null default false,
  sub_id bigint,
  dispute_reason text not null default '',
  dispute_by uuid,
  resolution text not null default '',
  reviewed boolean not null default false,
  created_at timestamptz not null default now(),
  deliver_by timestamptz not null,
  delivered_at timestamptz,
  complete_at timestamptz,
  closed_at timestamptz
);
create index on sauda.orders(buyer, created_at desc);
create index on sauda.orders(seller, created_at desc);
create index on sauda.orders(status, complete_at);

create table sauda.reviews (
  order_id bigint primary key references sauda.orders(id),
  seller uuid not null references sauda.users(id),
  buyer uuid not null references sauda.users(id),
  lot_id bigint not null,
  game text not null,
  stars smallint not null check (stars between 1 and 5),
  text text not null default '',
  reply text not null default '',
  created_at timestamptz not null default now(),
  replied_at timestamptz
);
create index on sauda.reviews(seller, created_at desc);

-- ───────────── переписка ─────────────
create table sauda.chats (
  id bigint generated by default as identity primary key,
  a uuid not null references sauda.users(id),
  b uuid not null references sauda.users(id),
  last_at timestamptz not null default now(),
  last_text text not null default '',
  last_kind text not null default 'text',
  last_sender uuid,
  unread_a int not null default 0,
  unread_b int not null default 0,
  unique (a, b),
  check (a < b)
);
create index on sauda.chats(a, last_at desc);
create index on sauda.chats(b, last_at desc);

create table sauda.messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null references sauda.chats(id) on delete cascade,
  sender uuid references sauda.users(id),
  kind text not null default 'text' check (kind in ('text', 'system', 'image')),
  body text not null,
  order_id bigint,
  created_at timestamptz not null default now()
);
create index on sauda.messages(chat_id, id);

-- ───────────── деньги ─────────────
create table sauda.tx (
  id bigint generated by default as identity primary key,
  user_id uuid not null references sauda.users(id),
  amount bigint not null,
  kind text not null,
  ref bigint,
  note text not null default '',
  balance_after bigint not null,
  created_at timestamptz not null default now()
);
create index on sauda.tx(user_id, id desc);

create table sauda.topups (
  id bigint generated by default as identity primary key,
  user_id uuid not null references sauda.users(id),
  amount bigint not null,
  method text not null,
  status text not null default 'pending' check (status in ('pending', 'paid', 'failed')),
  provider_ref text not null default '',
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create table sauda.withdrawals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references sauda.users(id),
  amount bigint not null,
  fee bigint not null default 0,
  method text not null check (method in ('kaspi', 'halyk', 'card', 'freedom')),
  details text not null,
  status text not null default 'pending' check (status in ('pending', 'done', 'rejected')),
  note text not null default '',
  test boolean not null default false,
  created_at timestamptz not null default now(),
  processed_at timestamptz
);
create index on sauda.withdrawals(status, created_at);

create table sauda.promos (
  code text primary key,
  amount bigint not null check (amount > 0),
  uses_left int not null default 1,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);
create table sauda.promo_uses (
  code text not null references sauda.promos(code) on delete cascade,
  user_id uuid not null references sauda.users(id),
  created_at timestamptz not null default now(),
  primary key (code, user_id)
);

-- автопродление подписок
create table sauda.subs (
  id bigint generated by default as identity primary key,
  buyer uuid not null references sauda.users(id),
  lot_id bigint not null references sauda.lots(id),
  buyer_data text not null default '',
  active boolean not null default true,
  next_at timestamptz not null,
  last_order bigint,
  fails int not null default 0,
  created_at timestamptz not null default now(),
  unique (buyer, lot_id)
);
create index on sauda.subs(active, next_at);

-- ───────────── прочее ─────────────
create table sauda.favs (
  user_id uuid not null references sauda.users(id) on delete cascade,
  lot_id bigint not null references sauda.lots(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, lot_id)
);

create table sauda.notifs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references sauda.users(id) on delete cascade,
  kind text not null,
  data jsonb not null default '{}',
  link text not null default '',
  read boolean not null default false,
  created_at timestamptz not null default now()
);
create index on sauda.notifs(user_id, id desc);

create table sauda.raises (
  seller uuid not null references sauda.users(id),
  game text not null,
  section text not null,
  at timestamptz not null default now(),
  primary key (seller, game, section)
);

create table sauda.reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references sauda.users(id),
  kind text not null check (kind in ('lot', 'user', 'order')),
  target text not null,
  text text not null,
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['config','state','users','sessions','games','lots','lot_items','orders','reviews','chats','messages',
                           'tx','topups','withdrawals','promos','promo_uses','subs','favs','notifs','raises','reports'] loop
    execute format('alter table sauda.%I enable row level security', t);
  end loop;
end $$;
revoke all on all tables in schema sauda from public, anon, authenticated;
revoke all on all sequences in schema sauda from public, anon, authenticated;
