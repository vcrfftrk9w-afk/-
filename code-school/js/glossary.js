// служебные дубли (gold_, map_, keys_) — чтобы не перетирать слова с другим значением
for (const k of Object.keys(window.GLOSSARY)) if (k.endsWith('_')) delete window.GLOSSARY[k];

// Короткая подсказка для слова: «console — консоль [ко́нсоул]»
window.glossLookup = function (word) {
  if (!word) return null;
  const g = window.GLOSSARY;
  if (Object.prototype.hasOwnProperty.call(g, word)) return { word, ru: g[word][0], say: g[word][1], what: g[word][2], topic: g[word][3] };
  // составные имена: playerSpeed → player + speed
  const parts = word.replace(/([a-z])([A-Z])/g, '$1 $2').split(/[\s_]+/).filter(Boolean);
  if (parts.length > 1) {
    const tr = parts.map((p) => {
      const low = p.toLowerCase();
      const hit = g[low] || g[p];
      return hit ? hit[0].split(/[,(]/)[0].trim() : null;
    });
    if (tr.every(Boolean)) return { word, ru: tr.join(' + '), say: parts.map((p) => (g[p.toLowerCase()] || g[p])[1]).join(' '), what: 'Составное имя: ' + parts.join(' + '), topic: '' };
  }
  return null;
};
