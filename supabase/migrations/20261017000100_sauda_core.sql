-- «Sauda» — маркетплейс игровых ценностей, доната, подписок и услуг для Казахстана.
-- Отдельная закрытая схема sauda; приложение (папка market/) ходит только через функции public.sauda_*.
-- Деньги — целые тенге. Каждое движение денег — строка в sauda.tx (журнал), баланс меняет только sauda.money().
-- Сделка через гаранта: покупатель платит → деньги заморожены в заказе → продавец выполняет →
-- покупатель подтверждает (или через N часов подтверждается само) → продавец получает сумму минус комиссию.

create extension if not exists pgcrypto with schema extensions;
create extension if not exists pg_trgm with schema extensions;

create schema if not exists sauda;
revoke all on schema sauda from public, anon, authenticated;

-- ───────────── настройки ─────────────
