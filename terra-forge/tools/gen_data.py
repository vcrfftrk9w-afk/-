"""Writes the generated Luau data modules.
Usage: python3 tools/gen_data.py <icons.json> <map.b64> [preview.png]
"""
import base64, json, sys

icons_json, map_b64 = sys.argv[1], sys.argv[2]
preview = sys.argv[3] if len(sys.argv) > 3 else None
ic = json.load(open(icons_json))

lines = ['-- Generated by tools/gen_data.py from tools/icons.js. Do not edit by hand.',
         '-- Each icon: palette (m/d/l = nation colour, letter = fixed slot colour, #hex = fixed) and',
         '-- base64 pixels, one byte per pixel: high 4 bits = palette index, low 4 bits = alpha (0-15).',
         'return {', f'\tsize = {ic["size"]},', '\tslots = {']
for k, v in ic['slots'].items():
    lines.append(f'\t\t{k} = "{v}",')
lines.append('\t},')
lines.append('\ticons = {')
for name, d in ic['icons'].items():
    pal = ', '.join(f'"{p}"' for p in d['palette'])
    lines.append(f'\t\t{name} = {{ palette = {{ {pal} }}, data = "{d["data"]}" }},')
lines += ['\t},', '}', '']
open('src/shared/Icons.luau', 'w').write('\n'.join(lines))

b64 = open(map_b64).read().strip()
open('src/shared/MapData.luau', 'w').write(
    '-- Generated by tools/gen_map.py from Natural Earth (public domain). Do not edit by hand.\n'
    '-- 720 x 336 tiles, Miller projection, 80N to 56S. Run-length encoded, base64:\n'
    '-- each byte = biome << 5 | (run length - 1). Biomes: 0 water, 1 grass, 2 desert, 3 mountain, 4 snow, 5 tundra.\n'
    f'return "{b64}"\n')

if preview:
    from PIL import Image
    S = ic['size']; names = list(ic['icons']); cols = 8
    img = Image.new('RGBA', (cols * (S + 8), ((len(names) + cols - 1) // cols) * (S + 8)), (40, 46, 60, 255))
    tint = {'m': (255, 62, 138), 'd': (173, 42, 94), 'l': (255, 156, 194)}
    def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
    for n, name in enumerate(names):
        d = ic['icons'][name]; raw = base64.b64decode(d['data'])
        tile = Image.new('RGBA', (S, S))
        px = tile.load()
        for i, v in enumerate(raw):
            a = v & 15
            if not a: continue
            p = d['palette'][v >> 4]
            c = tint[p] if p in tint else rgb(ic['slots'][p]) if len(p) == 1 else rgb(p)
            px[i % S, i // S] = (*c, a * 17)
        img.alpha_composite(tile, ((n % cols) * (S + 8) + 4, (n // cols) * (S + 8) + 4))
    img.save(preview)
print('ok')
