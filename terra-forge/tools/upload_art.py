"""Uploads the game's pictures to Roblox as decals through Open Cloud and writes their ids to
src/shared/MapArt.luau, by name. The game server turns decal ids into image ids at start.
The API key (assets read and write) comes from the cloud environment's network secret for
apis.roblox.com, or from ROBLOX_API_KEY.
Usage: python3 tools/upload_art.py name=path.png [name=path.png ...]
Names: map0..map5 (ground chunks, row by row), atlas (sprites), team (team-colour layer).
"""
import json
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = 'https://apis.roblox.com/assets/v1'
USER_ID = '11754622388'
OUT = os.path.join(ROOT, 'src', 'shared', 'MapArt.luau')


def curl(args):
    key = os.environ.get('ROBLOX_API_KEY')
    extra = ['-H', f'x-api-key: {key}'] if key else []
    out = subprocess.run(['curl', '-sS', '-m', '180'] + extra + args, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def upload(path, name):
    request = {
        'assetType': 'Decal',
        'displayName': f'Terra Forge {name}',
        'description': 'Terra Forge game art',
        'creationContext': {'creator': {'userId': USER_ID}},
    }
    op = curl(['-X', 'POST', f'{API}/assets', '-F', f'request={json.dumps(request)};type=application/json',
               '-F', f'fileContent=@{path};type=image/png'])
    if 'operationId' not in op:
        raise RuntimeError(f'upload failed: {op}')
    for _ in range(60):
        res = curl([f'{API}/operations/{op["operationId"]}'])
        if res.get('done'):
            return res['response']['assetId']
        time.sleep(2)
    raise RuntimeError('upload did not finish')


def read_existing():
    ids = {}
    if os.path.exists(OUT):
        for line in open(OUT, encoding='utf-8'):
            line = line.strip()
            if '=' in line and line.endswith(',') and not line.startswith('--'):
                k, v = line[:-1].split('=', 1)
                ids[k.strip()] = v.strip()
    return ids


def main():
    ids = read_existing()
    for arg in sys.argv[1:]:
        name, path = arg.split('=', 1)
        ids[name] = upload(path, name)
        print(name, ids[name])
    lines = ['-- Generated by tools/upload_art.py. Do not edit by hand.',
             '-- Decal ids of the game pictures, by name; the server finds the image inside each.',
             'return {']
    for name in sorted(ids):
        lines.append(f'\t{name} = {ids[name]},')
    lines += ['}', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))


if __name__ == '__main__':
    main()
