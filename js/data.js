    if (!p) return null;
    let cur = 0;
    try { cur = p.val(s, api) || 0; } catch (e) { cur = 0; }
    return { cur: Math.min(cur, p.goal), goal: p.goal, pct: Math.min(100, (cur / p.goal) * 100) };
