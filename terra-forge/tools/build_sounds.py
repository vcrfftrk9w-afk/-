"""Builds the game's sound effects into one file, art/sounds.ogg, and writes where each clip
starts to src/shared/SoundData.luau. The game plays one clip at a time from that file
(Sound.PlaybackRegion), so all effects take a single audio upload.

The sources are public-domain (CC0) packs from OpenGameArt.org; see art/CREDITS.md.
Usage: python3 tools/build_sounds.py SOURCE_DIR [--upload]
  SOURCE_DIR holds the downloaded packs (zips unpacked into folders, loose files as they are).
  --upload sends art/sounds.ogg to Roblox as an audio asset and stores its id.
"""
import os
import subprocess
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'art', 'sounds.ogg')
DATA = os.path.join(ROOT, 'src', 'shared', 'SoundData.luau')
RATE = 44100
GAP = 0.2

# name: (file inside SOURCE_DIR, longest length in seconds, loudness in dB below full scale)
CLIPS = {
    'rifle': ('sounds/sks.wav', 0.5, -4),
    'mg': ('25-CC0-bang-sfx/shot_03.ogg', 0.3, -5),
    'cannon': ('25-CC0-bang-sfx/cannon_03.ogg', 0.85, -2),
    'tower': ('25-CC0-bang-sfx/cannon_01.ogg', 1.2, -2),
    'artillery': ('Black_Powder.wav', 0.6, -1),
    'rocket': ('l.mp3', 1.0, -3),
    'flak': ('25-CC0-bang-sfx/bang_02.ogg', 0.9, -4),
    'boom': ('sci-fi_sounds/explosionCrunch_000.ogg', 0.8, -3),
    'bigboom': ('Chunky_Explosion.mp3', 2.6, 0),
    'build': ('100-CC0-SFX_0/tools_03.ogg', 0.65, -4),
    'hammer': ('100-CC0-SFX_0/metal_02.ogg', 0.3, -9),
    'built': ('kenney_interfaceSounds/confirmation_002.ogg', 0.6, -5),
    'ready': ('kenney_interfaceSounds/confirmation_001.ogg', 0.3, -6),
    'click': ('kenney_interfaceSounds/select_002.ogg', 0.1, -8),
    'order': ('kenney_interfaceSounds/drop_002.ogg', 0.2, -8),
    'error': ('kenney_interfaceSounds/error_004.ogg', 0.15, -5),
    'alarm': ('kenney_interfaceSounds/bong_001.ogg', 0.15, -3),
    'win': ('kenney_interfaceSounds/maximize_008.ogg', 0.3, -4),
    'lose': ('kenney_interfaceSounds/minimize_008.ogg', 0.3, -4),
}


def find(src, rel):
    """the file at rel, or one whose name ends like it (zips were unpacked with flattened paths)"""
    path = os.path.join(src, rel)
    if os.path.exists(path):
        return path
    folder, name = os.path.split(rel)
    base = os.path.join(src, folder)
    for f in sorted(os.listdir(base)):
        if f.endswith(name):
            return os.path.join(base, f)
    raise FileNotFoundError(rel)


def decode(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(RATE), '-f', 'f32le', '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32).copy()


def clip(samples, length, db):
    # start where it gets loud (skips quiet noise before the shot), keep at most length seconds,
    # fade the end, set the peak level
    loud = np.nonzero(np.abs(samples) > 0.25 * np.abs(samples).max())[0]
    start = max(0, loud[0] - int(0.02 * RATE)) if len(loud) else 0
    s = samples[start:start + int(length * RATE)]
    fade_in, fade_out = int(0.003 * RATE), min(len(s) // 3, int(0.12 * RATE))
    s[:fade_in] *= np.linspace(0, 1, fade_in)
    s[len(s) - fade_out:] *= np.linspace(1, 0, fade_out)
    return s / max(np.abs(s).max(), 1e-6) * 10 ** (db / 20)


def build(src):
    parts, lines = [], []
    pos = GAP
    parts.append(np.zeros(int(GAP * RATE), np.float32))
    for name, (rel, length, db) in CLIPS.items():
        s = clip(decode(find(src, rel)), length, db)
        lines.append(f'\t\t{name} = {{ {pos:.4f}, {len(s) / RATE:.4f} }},')
        parts.append(s)
        parts.append(np.zeros(int(GAP * RATE), np.float32))
        pos += len(s) / RATE + GAP
    audio = np.concatenate(parts)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ar', str(RATE), '-ac', '1', '-i', '-',
                    '-c:a', 'libvorbis', '-q:a', '6', OUT], input=audio.tobytes(), check=True)
    print(OUT, f'{len(audio) / RATE:.1f} s')
    return lines


def write_data(lines, asset_id):
    out = [
        '-- Generated by tools/build_sounds.py. Do not edit by hand.',
        '-- All sound effects are in one audio asset; each clip is { start, length } in seconds.',
        'return {',
        f'\tid = {asset_id},',
        '\tclips = {',
        *lines,
        '\t},',
        '}',
        '',
    ]
    open(DATA, 'w', encoding='utf-8').write('\n'.join(out))


def old_id():
    if os.path.exists(DATA):
        for line in open(DATA, encoding='utf-8'):
            if line.strip().startswith('id = '):
                return line.strip()[5:].rstrip(',')
    return '0'


def main():
    lines = build(sys.argv[1])
    asset_id = old_id()
    if '--upload' in sys.argv:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from upload_art import upload
        asset_id = upload(OUT, 'sounds', 'Audio', 'audio/ogg')
        print('audio asset', asset_id)
    write_data(lines, asset_id)


if __name__ == '__main__':
    main()
